import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';
import { subscribeCentralCommand } from '../src/Pages/dashboard/my-workspace/centralCommand.realtime.js';
import { chronologicalMessages } from '../src/Pages/dashboard/my-workspace/centralCommand.utils.js';

const socket = new EventEmitter();
socket.connected = true;
let calls = 0;
let release;
const statuses = [];
const errors = [];
const unrelated = () => {};
socket.on('central-command:changed', unrelated);
const subscription = subscribeCentralCommand(socket, async () => {
  calls++;
  if (calls === 1) await new Promise(resolve => { release = resolve; });
}, status => statuses.push(status), error => errors.push(error));
for (let i = 0; i < 10; i++) socket.emit('central-command:changed');
await delay(140);
assert.equal(calls, 1, 'burst is coalesced');
socket.emit('central-command:changed');
await delay(140);
assert.equal(calls, 1, 'refreshes never overlap');
release();
await delay(10);
assert.equal(calls, 2, 'hint during refresh is retained');
socket.emit('disconnect');
socket.emit('connect');
await delay(140);
assert.equal(calls, 3, 'reconnect catches up');
assert.deepEqual(statuses, ['connected', 'disconnected', 'connected']);
socket.emit('connect_error', new Error('offline'));
assert.equal(errors.length, 1);
socket.emit('central-command:changed');
subscription.dispose();
await delay(140);
assert.equal(calls, 3, 'cleanup cancels pending refresh');
assert.deepEqual(socket.listeners('central-command:changed'), [unrelated], 'other subscribers survive');
assert.equal(socket.listenerCount('connect'), 0);
assert.equal(socket.listenerCount('disconnect'), 0);
assert.equal(socket.listenerCount('connect_error'), 0);
const message = { _id: 'a', createdAt: '2026-10-28', text: 'old' };
assert.deepEqual(chronologicalMessages([{ items: [{ ...message, text: 'updated' }] }, { items: [message] }]), [{ ...message, text: 'updated' }]);
console.log('Workspace realtime checks passed.');
